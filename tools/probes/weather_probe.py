#!/usr/bin/env python3
"""Does Santa assume the weather where the child is? (live; the rule in persona._RULE_ADDITIONS forbids it)

Whole calls (started as the call page starts one) where the child never mentions weather. Emma's profile remembers
"likes snow angels" (a like the guide asks about); Leo has no remembered likes. A reply "assumes the weather" when a
sentence that does not mention the North Pole asks or says that it is snowy, cold, sunny or rainy where the child is
("Did you play in the snow today?", "...when it snows?"). Nothing is saved. Product code unchanged.

Usage: <venv>/bin/python tools/probes/weather_probe.py [--runs 3]    Writes tools/probes/out/weather_probe.md.
"""
import argparse
import copy
import os
import re
import sys
import tempfile
from datetime import datetime
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "out"
os.environ["SANTA_PROFILES"] = str(Path(tempfile.mkdtemp(prefix="santa-weather-")) / "profiles.json")
sys.path.insert(0, str(ROOT))

ap = argparse.ArgumentParser()
ap.add_argument("--runs", type=int, default=3)
A = ap.parse_args()

from santa import config, memory  # noqa: E402
from santa.brain import Santa  # noqa: E402
from santa.web import canned  # noqa: E402

KIDS = {"Emma": {"age": 4, "facts": ["likes snow angels"]}, "Leo": {"age": 3, "facts": []}}
LINES = ["good", "I played with my blocks", "my mom made pancakes", "I have a cat", "I like drawing",
         "we went to the park", "my friend came over", "yeah"]
WEATHER = re.compile(
    r"\b(?:play(?:ed|ing)?|went|go|going)\s+(?:out\s+)?in\s+the\s+snow\b|\bis\s+it\s+(?:snowing|cold|sunny|raining|snowy)"
    r"|\b(?:snowy|cold|chilly|sunny|rainy|snowing)\s+(?:day|outside|today|where\s+you)"
    r"|\b(?:when|if|while)\s+it(?:['’]s|\s+is)?\s+(?:snows?|snowing|snowy|cold|sunny|rains?|raining)\b"
    r"|\bcold\s+outside\b|\bsnow\s+(?:today|outside|where\s+you)|\bbundle[ds]?\s+up\b|\b(?:stay|keep)\s+warm\b"
    r"|\bsnow\s+day\b", re.I)
SENT = re.compile(r"[^.!?]+[.!?]*")


def assumes_weather(text: str) -> bool:
    return any(WEATHER.search(s) and not re.search(r"north\s+pole", s, re.I) for s in SENT.findall(text))


def main():
    memory.save = lambda *a, **k: None
    rows, hits, n = [], {"Emma": 0, "Leo": 0}, {"Emma": 0, "Leo": 0}
    for run in range(A.runs):
        for kid in KIDS:
            s = Santa(profiles=copy.deepcopy(KIDS))
            s.clock = lambda: datetime(2026, 11, 27, 16, 0)
            s.history.append({"role": "assistant", "content": canned.GREETING_SAID})
            for i, line in enumerate([f"I'm {kid}"] + LINES):
                kind = s._guide_kind(kid, line)
                r = s.reply_ex(kid, line)
                hit = assumes_weather(r.text)
                n[kid] += 1
                hits[kid] += hit
                rows.append(f"| {run + 1} | {kid} | {i + 1} | {kind or ''} | {line} | {r.text.replace('|', '/')} | "
                            f"{'WEATHER' if hit else ''} |")
                if hit:
                    print(f"[{run + 1} {kid} T{i + 1} {kind}] {line} -> {r.text}", flush=True)
    summary = [f"- {k}: {hits[k]}/{n[k]} replies assume the weather" for k in KIDS]
    OUT.mkdir(exist_ok=True)
    (OUT / "weather_probe.md").write_text("\n".join(
        ["# Weather assumptions (generated by tools/probes/weather_probe.py)\n",
         f"Model {config.MODEL}, {A.runs} runs, child never mentions weather.\n"] + summary +
        ["", "| run | child | turn | note | child said | Santa said | |", "|---|---|---|---|---|---|---|"] + rows) + "\n")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
