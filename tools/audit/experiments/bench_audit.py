"""Step 7: can the numbers in evals/bench_report.md be trusted / compared? (read-only)

1. Which scenarios in each result file were regenerated after the 22:41 backup (BENCH_ONLY merge)?
2. Were the judge scores made on the answer text that is stored now?
3. Do the content checks (recall / leak / name / persona) change if only the FILTER changes (stored answer vs
   current sanitize(raw))? -> model comparisons move without any model change.
4. What drives latency p95?
5. Which report claims are stale relative to the current bench code?
"""
import importlib.util
import json
import statistics
import sys
from collections import Counter, defaultdict

from _common import ROOT, load_turns, write

sys.dont_write_bytecode = True
spec = importlib.util.spec_from_file_location("bench_ro", ROOT / "evals" / "bench.py")
bench = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bench)  # note: patches santa.memory.save in THIS process only; we never call it
from santa import safety  # noqa: E402  (the real current package, imported read-only)

turns = load_turns()
L = ["# Benchmark audit (generated by bench_audit.py; read-only)\n"]

# 1. merge provenance
L.append("## 1. Which scenarios were regenerated after the 22:41 backup (BENCH_ONLY merge)\n")
bk = ROOT / "evals" / "backup" / "pre-fix-2241"
for f in sorted((ROOT / "evals" / "results").glob("ai_*.json")):
    cur = json.loads(f.read_text())
    old = json.loads((bk / f.name).read_text()) if (bk / f.name).exists() else None
    if not old:
        L.append(f"- {f.name}: no backup to compare")
        continue
    diff_raw = Counter()
    diff_ans = Counter()
    key = lambda t: (t["scenario"], t["sample"], t["idx"])  # noqa: E731
    om = {key(t): t for t in old["turns"]}
    for t in cur["turns"]:
        o = om.get(key(t))
        if o is None or o["raw"] != t["raw"]:
            diff_raw[t["scenario"]] += 1
        elif o["answer"] != t["answer"]:
            diff_ans[t["scenario"]] += 1
    L.append(f"- {f.name}: raw regenerated in {dict(diff_raw) or 'none'}; same raw but different stored answer "
             f"(re-sanitized) in {sum(diff_ans.values())} turns")

# 2. judge vs stored answers
L.append("\n## 2. Judge scores vs the answers stored now\n")
judge = json.loads((ROOT / "evals" / "results" / "judge.json").read_text())
L.append(f"- judge.json: {len(judge)} entries, {sum('hash' in v for v in judge.values())} with an answer hash, "
         f"judge model recorded: {sorted({v.get('judge_model', 'unrecorded') for v in judge.values()})}; files covered: "
         f"{sorted(Counter(k.split('|')[0] for k in judge))}")
oldj = json.loads((bk / "judge.json").read_text())
L.append(f"- judge.json identical to the 22:41 backup copy: {oldj == judge}")
changed = same = 0
for f in sorted(bk.glob("ai_*.json")):
    old = {(t["scenario"], t["sample"], t["idx"]): t for t in json.loads(f.read_text())["turns"]}
    cur = {(t["scenario"], t["sample"], t["idx"]): t for t in json.loads((ROOT / "evals/results" / f.name).read_text())["turns"]}
    slug = bench.slug(json.loads(f.read_text())["model"])
    for k in judge:
        if not k.startswith(slug + "|"):
            continue
        _, sc, s, i = k.split("|")
        kk = (sc, int(s), int(i))
        if kk in cur and kk in old:
            changed += cur[kk]["answer"] != old[kk]["answer"]
            same += cur[kk]["answer"] == old[kk]["answer"]
cs = sum(1 for t in turns if t.get("judge") and (bench.slug(t["model"]) + f"|{t['scenario']}|{t['sample']}|{t['idx']}") in judge
         and t["answer"] != safety.sanitize(t["raw"]))
L.append(f"- Of the judged turns, the stored answer differs from the 22:41 answer in {changed} and is the same in {same} "
         f"(the judge ran at 21:51, before even the 22:41 state, so 'same' is an upper bound on validity)")
L.append(f"- Judged turns whose stored answer differs from what the CURRENT filter would produce: {cs}")

# 3. checks move with the filter
L.append("\n## 3. Content checks recomputed on current sanitize(raw) vs the stored checks (no model change)\n")
spec_cases = json.loads((ROOT / "evals" / "cases.json").read_text())
cases = {c["id"]: c for c in spec_cases["cases"]}
scen = {sc["id"]: sc for sc in bench.SCENARIOS}
single_owned = bench.build_owned(spec_cases["profiles"])
owned = {sid: bench.scenario_owned(sc) for sid, sc in scen.items()}
flip = defaultdict(lambda: Counter())
rates = defaultdict(lambda: defaultdict(lambda: [0, 0, 0]))  # model -> check -> [n, stored_true, now_true]
for t in turns:
    ans_now = safety.sanitize(t["raw"])
    if t["kind"] == "single":
        now = bench.single_checks(cases[t["scenario"]], t["speaker"], ans_now, t["raw"], single_owned)
        stored = bench.single_checks(cases[t["scenario"]], t["speaker"], t["answer"], t["raw"], single_owned)
    else:
        tn = scen[t["scenario"]]["turns"][t["idx"]]
        now = bench.turn_checks(tn, tn["s"], tn["t"], ans_now, t["raw"], owned[t["scenario"]])
        stored = bench.turn_checks(tn, tn["s"], tn["t"], t["answer"], t["raw"], owned[t["scenario"]])
    for c in set(now) | set(stored):
        r = rates[t["short"]][c]
        r[0] += 1
        r[1] += bool(stored.get(c))
        r[2] += bool(now.get(c))
        if stored.get(c) != now.get(c):
            flip[t["short"]][c] += 1
L.append("| File | check | n | pass % with stored answer (s0 filter) | pass % with current filter | flips |")
L.append("|---|---|---|---|---|---|")
for m in sorted(rates):
    for c, (n, a, b) in sorted(rates[m].items()):
        if a != b:
            L.append(f"| {m} | {c} | {n} | {100*a/n:.1f} | {100*b/n:.1f} | {flip[m][c]} |")
L.append("\nOnly rows where the pass rate changed are shown. The model output is identical; only the filter differs.")

# recall-specific example
ex = []
for t in turns:
    if t["kind"] == "multi" and t.get("cat") in ("recall", "long_recall"):
        tn = scen[t["scenario"]]["turns"][t["idx"]]
        a = bench.turn_checks(tn, tn["s"], tn["t"], t["answer"], t["raw"], owned[t["scenario"]]).get("recall")
        b = bench.turn_checks(tn, tn["s"], tn["t"], safety.sanitize(t["raw"]), t["raw"], owned[t["scenario"]]).get("recall")
        if a != b:
            ex.append((t, a, b))
for t, a, b in ex[:4]:
    L.append(f"- [{t['short']}] recall stored={a} now={b}; child: {t['child']!r}\n  - raw: {t['raw'][:220]!r}\n"
             f"  - current heard: {safety.sanitize(t['raw'])!r}")

# 4. latency drivers
L.append("\n## 4. What drives latency p95 (stored timings)\n")
L.append("| File | TTFT p50 single | TTFT p50 multi | TTFT p95 first turn of a session | TTFT p95 later turns | total p50 single | total p50 multi |")
L.append("|---|---|---|---|---|---|---|")
for m in sorted({t["short"] for t in turns}):
    R = [t for t in turns if t["short"] == m]
    first = [t["ttft"] for t in R if t["idx"] == 0]
    later = [t["ttft"] for t in R if t["idx"] > 0]
    q = lambda xs, p: sorted(xs)[int(round(p / 100 * (len(xs) - 1)))]  # noqa: E731
    L.append(f"| {m} | {statistics.median([t['ttft'] for t in R if t['kind']=='single']):.2f} | "
             f"{statistics.median([t['ttft'] for t in R if t['kind']=='multi']):.2f} | {q(first,95):.2f} | "
             f"{q(later,95):.2f} | {statistics.median([t['total'] for t in R if t['kind']=='single']):.2f} | "
             f"{statistics.median([t['total'] for t in R if t['kind']=='multi']):.2f} |")

# 5. stale report claims
rep = (ROOT / "evals" / "bench_report.md").read_text()
L.append("\n## 5. Is bench_report.md produced by the current bench.py?\n")
L.append(f"- contains '(n=' (current report() prints n): {'(n=' in rep}")
L.append(f"- contains 'different model family from contestants' (removed in round 1): "
         f"{'different model family' in rep}")
L.append(f"- contains an 'Errors' row (added in round 1): {'Errors (' in rep}")
L.append(f"- model columns: {rep.splitlines()[4].count('|') - 2}; result files: "
         f"{len(list((ROOT/'evals'/'results').glob('ai_*.json')))}")
write("bench_audit.md", "\n".join(L) + "\n")
