"""Step 1: churn per file and per function across code versions (read-only).

Rounds:
  R0  idx -> s0   (git index 21:10 -> pre-fix snapshot 23:26; the undocumented "already fixed" session)
  R1  s0  -> s1   (FIXES.md)
  R2  s1  -> s2   (FIXES2.md)
  R3  s2  -> cur  (FIXES3.md)
bench.py is not in the git index; for R0 we use evals/backup/20261104-2110/bench.py instead.
"""
import ast
import difflib
import re
import subprocess
from collections import defaultdict

from _common import ROOT, SNAP, write

FILES = ["santa/safety.py", "santa/brain.py", "santa/memory.py", "santa/persona.py", "santa/config.py",
         "chat.py", "evals/bench.py", "evals/bench_all.sh", "evals/cases.json"]
ORDER = ["idx", "s0", "s1", "s2", "cur"]
ROUNDS = [("R0", "idx", "s0"), ("R1", "s0", "s1"), ("R2", "s1", "s2"), ("R3", "s2", "cur")]


def src(tag, rel):
    if tag == "idx":
        if rel == "evals/bench.py":
            p = ROOT / "evals/backup/20261104-2110/bench.py"
            return p.read_text()
        r = subprocess.run(["git", "-C", str(ROOT), "show", f":{rel}"], capture_output=True, text=True)
        return r.stdout if r.returncode == 0 else None
    p = SNAP[tag] / rel
    return p.read_text() if p.exists() else None


def diffstat(a, b):
    a, b = (a or "").splitlines(), (b or "").splitlines()
    add = rem = 0
    for line in difflib.unified_diff(a, b, lineterm="", n=0):
        if line.startswith("+") and not line.startswith("+++"):
            add += 1
        elif line.startswith("-") and not line.startswith("---"):
            rem += 1
    return add, rem


def units(code):
    """{qualified name: source} for top-level functions, methods and top-level assignments."""
    out = {}
    if code is None:
        return out
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return out
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out[node.name + "()"] = ast.get_source_segment(code, node)
        elif isinstance(node, ast.ClassDef):
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    out[f"{node.name}.{sub.name}()"] = ast.get_source_segment(code, sub)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for t in targets:
                if isinstance(t, ast.Name):
                    out[t.id] = ast.get_source_segment(code, node)
    return out


lines = ["# Churn analysis (generated by churn.py)\n"]
# ---- file level
lines.append("## File-level line churn per round (+added / -removed)\n")
lines.append("| File | " + " | ".join(f"{r} {a}->{b}" for r, a, b in ROUNDS) + " | lines idx/s0 -> cur |")
lines.append("|---|" + "---|" * (len(ROUNDS) + 1))
tot = defaultdict(lambda: [0, 0])
for f in FILES:
    cells = []
    for r, a, b in ROUNDS:
        sa, sb = src(a, f), src(b, f)
        if sa is None and sb is None:
            cells.append("n/a")
            continue
        ad, rm = diffstat(sa, sb)
        tot[r][0] += ad
        tot[r][1] += rm
        cells.append(f"+{ad}/-{rm}" if (ad or rm) else "0")
    first = src("idx", f) or src("s0", f)
    lines.append(f"| {f} | " + " | ".join(cells) +
                 f" | {len((first or '').splitlines())} -> {len((src('cur', f) or '').splitlines())} |")
lines.append("| **total** | " + " | ".join(f"+{tot[r][0]}/-{tot[r][1]}" for r, _, _ in ROUNDS) + " | |")

# ---- function level
lines.append("\n## Function / constant-level: which units changed in which round\n")
touched = defaultdict(list)
for f in FILES:
    if not f.endswith(".py"):
        continue
    vers = {t: units(src(t, f)) for t in ORDER}
    names = set().union(*[set(v) for v in vers.values()])
    for n in sorted(names):
        for r, a, b in ROUNDS:
            ua, ub = vers[a].get(n), vers[b].get(n)
            if ua != ub:
                kind = "added" if ua is None else "removed" if ub is None else "changed"
                ad, rm = diffstat(ua, ub)
                touched[(f, n)].append(f"{r}:{kind}(+{ad}/-{rm})")
hot = sorted(touched.items(), key=lambda kv: (-len(kv[1]), kv[0]))
lines.append("| File | Unit | # rounds touched | Rounds |")
lines.append("|---|---|---|---|")
for (f, n), rs in hot:
    if len(rs) >= 2:
        lines.append(f"| {f} | `{n}` | {len(rs)} | {'; '.join(rs)} |")
lines.append("")
lines.append(f"Units touched in >=2 rounds: {sum(1 for _, rs in hot if len(rs) >= 2)}; "
             f">=3 rounds: {sum(1 for _, rs in hot if len(rs) >= 3)}; total units touched: {len(hot)}")

# ---- order of passes inside sanitize, per version
lines.append("\n## The sanitize pipeline, per version (the composition line)\n")
for t in ORDER:
    s = src(t, "santa/safety.py")
    m = re.findall(r"^\s+text = (_[a-z_]+\(.*\))\s*$", s, re.M)
    lines.append(f"- {t}: " + ("; ".join(x for x in m if "(" in x) or "?"))

# ---- tests per round
lines.append("\n## Test functions per version (AST count of `def test_*`, before parametrization)\n")
TEST_ORDER = ["s0", "s1", "s2", "cur"]


def test_units(tag):
    d = (SNAP[tag] / "tests" / "review")
    out = {}
    for p in sorted(d.glob("test_*.py")):
        code = p.read_text()
        for node in ast.walk(ast.parse(code)):
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                seg = ast.get_source_segment(code, node)
                decos = [ast.get_source_segment(code, dd) for dd in node.decorator_list]
                out[f"{p.name}::{node.name}"] = (seg, decos)
    return out


tv = {t: test_units(t) for t in TEST_ORDER}
lines.append("| Version | test files | test functions | with xfail marker |")
lines.append("|---|---|---|---|")
for t in TEST_ORDER:
    files = {k.split("::")[0] for k in tv[t]}
    xf = sum(1 for _, (s, d) in tv[t].items() if any("xfail" in x for x in d))
    lines.append(f"| {t} | {len(files)} | {len(tv[t])} | {xf} |")
lines.append("\n| Transition | test fns added | removed | body changed (excluding decorator-only) | decorator-only changes |")
lines.append("|---|---|---|---|---|")
for a, b in zip(TEST_ORDER, TEST_ORDER[1:]):
    A, B = tv[a], tv[b]
    added = [k for k in B if k not in A]
    removed = [k for k in A if k not in B]
    body = []
    deco = []
    for k in set(A) & set(B):
        (sa, da), (sb, db) = A[k], B[k]
        strip = lambda s: "\n".join(l for l in s.splitlines() if not l.strip().startswith("@"))  # noqa: E731
        if strip(sa) != strip(sb):
            body.append(k)
        elif da != db:
            deco.append(k)
    lines.append(f"| {a}->{b} | {len(added)} | {len(removed)} | {len(body)} {sorted(body)} | {len(deco)} |")

write("churn.md", "\n".join(lines) + "\n")
