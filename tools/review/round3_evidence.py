#!/usr/bin/env python3
"""Evidence for round 3 (read-only, no model calls).

Replays the stored RAW model replies in evals/results/ai_*.json through the CURRENT santa.safety.sanitize_ex and,
for comparison, through the round-2 version kept in .snapshots/pre-fix3-*, then writes
docs/history/round3_examples.md. Nothing else is written; evals/results is only read.

    <venv>/bin/python tools/review/round3_evidence.py
"""
import collections
import difflib
import glob
import importlib
import json
import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "history" / "round3_examples.md"
sys.path.insert(0, str(ROOT))

from santa import config, safety  # noqa: E402  (current code)

# Numbers printed in FIXES2.md section 5 (round 2), for reference next to the recomputed ones.
FIXES2 = {"no question": "49.9%", "one question": "50.1%", "lone echo": "0.9%", "fallbacks": "2"}


def load_round2():
    """The round-2 santa package from the newest pre-fix3 snapshot, imported under another name.
    (santa/ has no __init__.py, so build an empty package whose __path__ is the snapshot folder.)"""
    snaps = sorted((ROOT / ".snapshots").glob("pre-fix3-*/santa/safety.py"))
    if not snaps:
        return None
    pkg = types.ModuleType("santa_round2")
    pkg.__path__ = [str(snaps[-1].parent)]
    sys.modules["santa_round2"] = pkg
    return importlib.import_module("santa_round2.safety"), importlib.import_module("santa_round2.config")


def qsents(mod, text):
    return [s for s in mod._SENT_SPLIT.split(text) if "?" in s]


def stats(mod, cfg, replies):
    c = collections.Counter()
    why = collections.Counter()
    words = sents = 0
    for raw in replies:
        ans, reason = mod.sanitize_ex(raw)
        n = ans.count("?")
        c["q0" if n == 0 else "q1" if n == 1 else "q2"] += 1
        if reason:
            c["fallback"] += 1
            why[reason] += 1
        qs = qsents(mod, ans)
        if len(qs) == 1 and n == 1 and len(qs[0].split()) <= 4:
            c["echo"] += 1
        words += len(ans.split())
        sents += len(mod._SENT_SPLIT.split(ans))
        keep = cfg.MAX_WORDS
        cfg.MAX_WORDS = 10 ** 6                       # what the reply would be without the word cap
        try:
            uncapped, _ = mod.sanitize_ex(raw)
        finally:
            cfg.MAX_WORDS = keep
        if len(uncapped.split()) > keep:
            c["wordcut"] += 1
    c["words"], c["sents"] = words, sents
    return c, why


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ").strip()


def note(raw, ans, reason):
    parts = []
    if reason:
        parts.append(f"replaced by fallback ({reason})")
    else:
        rq, aq = raw.count("?"), ans.count("?")
        if rq != aq:
            parts.append(f"'?' x{rq} -> x{aq}")
        cut = len(safety._SENT_SPLIT.split(safety._clean(raw))) - len(safety._SENT_SPLIT.split(ans))
        if cut > 0:
            parts.append(f"{cut} sentence(s) dropped")
        if safety._clean(raw) != " ".join(raw.split()):
            parts.append("markup/stage directions cleaned")
    return "; ".join(parts) or "unchanged apart from whitespace"


def main():
    files = {Path(f).name: json.load(open(f)) for f in sorted(glob.glob(str(ROOT / "evals" / "results" / "ai_*.json")))}
    r2mod, r2cfg = load_round2() or (None, None)
    rows = []   # dict per non-empty raw reply
    for name, d in files.items():
        for t in d["turns"]:
            raw = t["raw"]
            if not raw.strip():
                continue
            ans, reason = safety.sanitize_ex(raw)
            old = r2mod.sanitize_ex(raw)[0] if r2mod else None
            rows.append({"file": name, "speaker": t["speaker"], "child": t["child"], "raw": raw, "ans": ans,
                         "reason": reason, "old": old,
                         "change": 1 - difflib.SequenceMatcher(None, " ".join(raw.split()), ans).ratio()})
    raws = [r["raw"] for r in rows]
    n = len(raws)
    cur, cur_why = stats(safety, config, raws)
    old, old_why = stats(r2mod, r2cfg, raws) if r2mod else (None, None)
    raw_q = collections.Counter(min(2, r.count("?")) for r in raws)

    def pct(x):
        return f"{x} ({100 * x / n:.1f}%)"

    def avg(c, key):
        return f"{c[key] / n:.2f}"

    md = ["# Round 3 evidence: what the child would hear",
          "",
          "Generated by `tools/review/round3_evidence.py` (read-only on `evals/results/`, no model calls).",
          f"Input: the {n} non-empty stored RAW replies from {len(files)} result files (v1/v2 personas, so this shows what "
          "the *filter* does to old-style replies, not what persona v3 will produce).",
          "",
          "## 1. Counts: round 2 vs now",
          "",
          "| Measure | Raw model output | Round 2 `sanitize` (recomputed from the snapshot) | Round 2 as printed in FIXES2.md | Now |",
          "|---|---|---|---|---|"]

    def row(label, raw_v, old_v, doc_v, cur_v):
        md.append(f"| {label} | {raw_v} | {old_v} | {doc_v} | {cur_v} |")

    o = (lambda k: pct(old[k])) if old else (lambda k: "n/a")
    row("0 question marks", pct(raw_q[0]), o("q0"), FIXES2["no question"], pct(cur["q0"]))
    row("exactly 1 question mark", pct(raw_q[1]), o("q1"), FIXES2["one question"], pct(cur["q1"]))
    row("more than 1 question mark", pct(raw_q[2]), o("q2"), "0.0%", pct(cur["q2"]))
    row("replaced by the fallback line", "n/a", o("fallback"), FIXES2["fallbacks"], pct(cur["fallback"]))
    row("lone short echo question (only question, 4 words or fewer)", "n/a", o("echo"), FIXES2["lone echo"], pct(cur["echo"]))
    row("average words heard", f"{sum(len(r.split()) for r in raws) / n:.2f}", avg(old, "words") if old else "n/a", "n/a", avg(cur, "words"))
    row("average sentences heard", f"{sum(len(safety._SENT_SPLIT.split(' '.join(r.split()))) for r in raws) / n:.2f}",
        avg(old, "sents") if old else "n/a", "n/a", avg(cur, "sents"))
    row("replies cut by the word cap (45 words)", "n/a", o("wordcut"), "n/a", pct(cur["wordcut"]))
    md += ["",
           "Fallback reasons (now): " + (", ".join(f"{k}: {v}" for k, v in cur_why.most_common()) or "none"),
           "",
           "Fallback reasons (round 2): " + (", ".join(f"{k}: {v}" for k, v in old_why.most_common()) or "none") if old
           else "Round-2 snapshot not found.",
           ""]

    def top(pred, k, used, key, per_file=None):
        picked, per = [], collections.Counter()
        for r in sorted((r for r in rows if pred(r)), key=lambda r: -key(r)):
            sig = " ".join(r["raw"].split())
            if sig in used or (per_file and per[r["file"]] >= per_file):
                continue
            used.add(sig)
            per[r["file"]] += 1
            picked.append(r)
            if len(picked) == k:
                break
        return picked

    def table(items):
        out = ["| # | File | Child said | Raw model reply | What the child hears now | What changed | Round 2 would have said |",
               "|---|---|---|---|---|---|---|"]
        for i, r in enumerate(items, 1):
            out.append(f"| {i} | {r['file'].replace('ai_', '').replace('.json', '')} | "
                       f"{cell(str(r['speaker']) + ': ' + r['child'])} | {cell(r['raw'])} | {cell(r['ans'])} | "
                       f"{cell(note(r['raw'], r['ans'], r['reason']))} | "
                       f"{cell(r['old']) if r['old'] is not None else 'n/a'} |")
        return out

    used = set()
    chg = lambda r: r["change"]  # noqa: E731
    examples = (top(lambda r: r["file"] == "ai_gemma4_e4b_v2.json", 10, used, chg)
                + top(lambda r: r["file"] == "ai_gemma4_v2.json", 5, used, chg)
                + top(lambda r: "ministral" in r["file"].lower(), 5, used, chg))
    md += ["## 2. The same twenty-example selection as round 2",
           "",
           "10 from `ai_gemma4_e4b_v2`, 5 from `ai_gemma4_v2`, 5 from the Ministral files; within each group the replies the "
           "current sanitize changed the most (difflib similarity of raw vs. what the child hears). Because the rule is "
           "applied to the current filter, the set differs somewhat from round 2's.",
           ""] + table(examples)

    def opens_ho(r):
        raw = " ".join(r["raw"].split())
        return raw.startswith("Ho ho ho!") and len(safety._SENT_SPLIT.split(raw)) >= 4

    def vs_round2(r):
        return 1 - difflib.SequenceMatcher(None, r["old"] or "", r["ans"]).ratio() if r["old"] is not None else r["change"]

    extra = top(opens_ho, 10, used, vs_round2, per_file=2)
    total_ho = sum(1 for r in rows if opens_ho(r))
    md += ["",
           f"## 3. Ten extra examples: replies that START with \"Ho ho ho!\" and have 4 or more sentences ({total_ho} such replies)",
           "",
           "Chosen as the ones where the child's experience changed most from round 2 to now (at most 2 per result file; "
           "not repeated from section 2).",
           ""] + table(extra)
    OUT.write_text("\n".join(md) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({n} replies, {len(examples)} + {len(extra)} examples)")


if __name__ == "__main__":
    main()
