"""Prototype (audit only, NOT product code): a remove-only, prefix-only filter that can run sentence by sentence
on a token stream, scored on the 924 stored raw replies with the same classifier as quality.py.

speak(raw):
  1. clean markup the same way the current _clean does, plus: delete a stand-alone *span* / (span) that sits
     between sentences unless it is only sound words ("jingle jingle", "whoosh"); inline emphasis is kept.
  2. walk sentences IN ORDER (what a streaming TTS would receive). For each sentence:
       - an action-only sentence ("Giggles.") is skipped
       - blocklist / private hit -> stop here (if nothing was kept yet -> FALLBACK)
       - stop BEFORE a sentence that would exceed opener + MAX_SENTENCES content sentences or MAX_WORDS words
         (only if the very first sentence is longer than MAX_WORDS is it cut by words)
  3. drop a trailing teaser ("You know what?") -- needs one sentence of look-ahead, fine for streaming
  Never rewrites '?' and never drops a middle sentence.
"""
import re
from collections import Counter

from _common import SOUNDS, W, load_safety, load_turns, write
from quality import ARTIFACT, LOST, MATERIAL, classify

S = load_safety("cur")
cfg = __import__("santa_cur.config", fromlist=["x"])


def _drop_standalone(raw):
    def repl(m):
        inner = m.group(1) if m.group(1) is not None else m.group(2)
        before = raw[:m.start()].rstrip()
        after = raw[m.end():].lstrip()
        alone_b = (not before) or before[-1] in ".!?…—-"
        alone_a = (not after) or after[0].isupper() or after[0] in ".!?…—-\n"
        if alone_b and alone_a and not all(w in SOUNDS for w in W(inner)):
            return " "
        return m.group(0)
    return re.sub(r"\*+([^*]+?)\*+|\(([^)]*)\)", repl, raw)


def speak(raw):
    text = S._clean(_drop_standalone(raw))
    kept, words, content = [], 0, 0
    for i, s in enumerate(x for x in S._SENT_SPLIT.split(text) if x.strip()):
        if re.fullmatch(rf"(?:{S._BARE})\W*", s, re.I):
            continue
        if S._BLOCK_RE.search(s) or S.looks_private(s):
            break
        is_open = not kept and S._is_opener(s)
        n = len(s.split())
        if kept and (words + n > cfg.MAX_WORDS or (not is_open and content + 1 > cfg.MAX_SENTENCES)):
            break
        if not kept and n > cfg.MAX_WORDS:
            kept.append(" ".join(s.split()[:cfg.MAX_WORDS]) + "…")
            break
        kept.append(s)
        words += n
        content += 0 if is_open else 1
    while len(kept) > 1 and S._TEASER_RE.match(kept[-1].strip()):
        kept.pop()
    if not kept:
        return S.FALLBACK
    return " ".join(kept)


turns = load_turns()
N = len(turns)
res = {"current": [], "prefix": []}
for t in turns:
    for name, fn in (("current", S.sanitize), ("prefix", speak)):
        h = fn(t["raw"])
        res[name].append((t, h, classify(t, h, S.FALLBACK)))

L = ["# Prototype remove-only prefix filter vs current sanitize (generated by prefix_filter_prototype.py)\n",
     "Same 924 stored raw replies, same heuristic classifier (quality.py). Prototype lives only in tests/audit.\n",
     "| Metric | current sanitize | prefix prototype |", "|---|---|---|"]


def row(label, f):
    a = sum(1 for x in res["current"] if f(x))
    b = sum(1 for x in res["prefix"] if f(x))
    L.append(f"| {label} | {a} ({100*a/N:.1f}%) | {b} ({100*b/N:.1f}%) |")


row("material change (intervention)", lambda x: x[2] & MATERIAL)
row("sentences dropped", lambda x: "dropped" in x[2])
row("question demoted to statement", lambda x: "q_demoted" in x[2])
row("no '?' in heard reply", lambda x: "?" not in x[1])
row("more than one '?' in heard reply", lambda x: x[1].count("?") > 1)
row("fallback", lambda x: "fallback" in x[2])
row("artifact: punctuation debris", lambda x: "art_punct" in x[2])
row("artifact: dangling Or/And/But", lambda x: "art_dangling" in x[2])
row("artifact: stage direction spoken", lambda x: "art_stage" in x[2])
row("answer lost (heuristic)", lambda x: "answer_lost" in x[2])
row("echo + question with middle dropped", lambda x: "echo_q" in x[2])
row("any artifact or answer lost", lambda x: x[2] & (ARTIFACT | LOST))
row(f"words > {cfg.MAX_WORDS}", lambda x: len(x[1].split()) > cfg.MAX_WORDS)
L.append("\nBy file (any artifact or answer lost / more than one '?'):\n")
L.append("| File | current | prefix |")
L.append("|---|---|---|")
for f in sorted({t["file"] for t in turns}):
    c = [x for x in res["current"] if x[0]["file"] == f]
    p = [x for x in res["prefix"] if x[0]["file"] == f]
    L.append(f"| {c[0][0]['short']} | {sum(1 for x in c if x[2] & (ARTIFACT|LOST))} / {sum(1 for x in c if x[1].count('?')>1)} | "
             f"{sum(1 for x in p if x[2] & (ARTIFACT|LOST))} / {sum(1 for x in p if x[1].count('?')>1)} |")

L.append("\n## The goldfish case and the other worst items from labels60.md, both filters\n")
for t, h, _ in res["prefix"]:
    key = (t["short"], t["scenario"], t["sample"], t["idx"])
    if key in {("ministral8B-instr v2", "dead", 0, 0), ("e4b v2", "recall", 2, 0), ("ministral8B-Q4 v2", "reindeer", 0, 0),
               ("gemma4-12B v2", "bossy", 1, 0), ("ministral8B-Q4 v2", "wish_multi", 2, 0)}:
        cur = S.sanitize(t["raw"])
        L.append(f"- [{t['short']}] {t['scenario']}: child {t['child']!r}\n  - current: {cur!r}\n  - prefix:  {h!r}")
write("prefix_prototype.md", "\n".join(L) + "\n")
