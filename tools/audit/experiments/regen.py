"""Step 5: repair vs regenerate vs constrain, from the stored replies and timings only (no model calls).

Validity used here ("acceptable with a remove-only post-filter"), applied to clean(raw) where clean = the current
_clean (unwrap emphasis, strip markdown/emoji, delete action-only spans):
  - no blocklist hit, not private
  - at most one '?'
  - at most MAX_SENTENCES content sentences (a leading interjection opener is free)
  - at most MAX_WORDS words
  - no stand-alone stage direction left over (a *span* / (span) alone between sentences that is not a sound word)
  - raw ends at a sentence end (not cut off by max_tokens)
"strict" additionally requires that clean(raw) == raw (no markup at all).
"""
import random
import re
import statistics
from collections import defaultdict

from _common import SOUNDS, W, load_safety, load_turns, standalone_spans, write

S = load_safety("cur")
cfg = __import__("santa_cur.config", fromlist=["x"])
turns = load_turns()


def content_sentences(text):
    ss = [x for x in S._SENT_SPLIT.split(text) if x.strip()]
    return ss[1:] if len(ss) > 1 and S._is_opener(ss[0]) else ss


def ends_complete(raw):
    return bool(re.search(r"[.!?…][\"'”’)*\s]*$", raw.strip()))


def leftover(raw):
    return any(W(i) and not S._is_direction(i) and not all(w in SOUNDS for w in W(i)) for i in standalone_spans(raw))


def why_invalid(raw, text=None):
    c = S._clean(raw) if text is None else text
    r = []
    if S._BLOCK_RE.search(c):
        r.append("blocklist")
    if S.looks_private(c):
        r.append("private")
    if c.count("?") > 1:
        r.append("questions>1")
    if len(content_sentences(c)) > cfg.MAX_SENTENCES:
        r.append("sentences>3")
    if len(c.split()) > cfg.MAX_WORDS:
        r.append("words>45")
    if text is None and leftover(raw):
        r.append("stage_leftover")
    if text is None and not ends_complete(raw):
        r.append("cut_by_max_tokens")
    if not c.strip():
        r.append("empty")
    return r


def pct(xs, p):
    xs = sorted(xs)
    if not xs:
        return float("nan")
    k = (len(xs) - 1) * p / 100
    f = int(k)
    return xs[f] + (xs[min(f + 1, len(xs) - 1)] - xs[f]) * (k - f)


for t in turns:
    t["why"] = why_invalid(t["raw"])
    t["ok"] = not t["why"]
    t["strict"] = t["ok"] and " ".join(S._clean(t["raw"]).split()) == " ".join(t["raw"].split())
    ss = [x for x in S._SENT_SPLIT.split(t["raw"].strip()) if x.strip()]
    first = ss[0] if ss else ""
    if len(ss) > 1 and S._is_opener(S._clean(first)):
        first = " ".join(ss[:2])
    frac = len(first) / max(1, len(t["raw"]))
    t["first_sentence_s"] = t["ttft"] + (t["total"] - t["ttft"]) * frac  # linear-in-characters estimate

files = sorted({t["file"] for t in turns})
L = ["# Repair vs regenerate vs constrain (generated by regen.py; stored data only)\n",
     "Validity = 'acceptable with a remove-only post-filter' (definition in the regen.py docstring).\n",
     "## Pass rates and latency per result file\n",
     "| File | n | strict pass (no change at all) | pass after remove-only clean | top reasons for failing | "
     "full reply p50 / p95 (s) | TTFT p50 / p95 (s) | est. first sentence p50 / p95 (s) | cut by max_tokens |",
     "|---|---|---|---|---|---|---|---|---|"]
for f in files:
    R = [t for t in turns if t["file"] == f]
    n = len(R)
    reasons = defaultdict(int)
    for t in R:
        for w in t["why"]:
            reasons[w] += 1
    top = ", ".join(f"{k} {v}" for k, v in sorted(reasons.items(), key=lambda kv: -kv[1])[:4])
    tot = [t["total"] for t in R]
    tt = [t["ttft"] for t in R]
    fs = [t["first_sentence_s"] for t in R]
    L.append(f"| {R[0]['short']} | {n} | {sum(t['strict'] for t in R)} ({100*sum(t['strict'] for t in R)/n:.0f}%) | "
             f"{sum(t['ok'] for t in R)} ({100*sum(t['ok'] for t in R)/n:.0f}%) | {top} | "
             f"{pct(tot,50):.2f} / {pct(tot,95):.2f} | {pct(tt,50):.2f} / {pct(tt,95):.2f} | "
             f"{pct(fs,50):.2f} / {pct(fs,95):.2f} | {reasons['cut_by_max_tokens']} |")
L.append("\nLatency caveat: the stored timings include cold-ish first requests (TTFT p95 is 3.5-11.6 s) and were "
         "measured with the 120-token cap; p95 is dominated by a few slow turns, not by reply length.")

# ------------------------------------------------------------------ P(second passes | first fails)
L.append("\n## Does a second sample pass when the first fails? (3 samples per case)\n")
L.append("Single-turn cases only (identical prompt across samples). Ordered pairs (i, j), i != j, within a case.\n")
L.append("| File | cases | unconditional pass | P(pass j given fail i) | ordered pairs with fail i | P(all 3 fail) |")
L.append("|---|---|---|---|---|---|")
pooled = {"pairs": 0, "pass": 0}
for f in files:
    by_case = defaultdict(list)
    for t in turns:
        if t["file"] == f and t["kind"] == "single":
            by_case[t["scenario"]].append(t["ok"])
    pairs = passes = 0
    allfail = 0
    for v in by_case.values():
        for i in range(len(v)):
            for j in range(len(v)):
                if i != j and not v[i]:
                    pairs += 1
                    passes += v[j]
        allfail += all(not x for x in v)
    unc = sum(sum(v) for v in by_case.values()) / sum(len(v) for v in by_case.values())
    pooled["pairs"] += pairs
    pooled["pass"] += passes
    L.append(f"| {next(t['short'] for t in turns if t['file'] == f)} | {len(by_case)} | {100*unc:.0f}% | "
             f"{(100*passes/pairs) if pairs else float('nan'):.0f}% | {pairs} | {allfail}/{len(by_case)} |")
L.append("\nHow weak this is: 20 cases x 3 samples per model; samples within a case are not independent of the case; "
         "a failing case tends to fail again (compare the conditional and unconditional columns). Treat as +/- 15 points.")

# ------------------------------------------------------------------ expected latency of validate-and-regenerate
L.append("\n## Simulated latency of design B (validate full reply, regenerate up to K-1 times, then fallback)\n")
L.append("Resampling stored samples of the SAME case (with replacement, 20 000 draws per file); a retry costs another "
         "full reply. Fallback after K attempts costs nothing extra.\n")
L.append("| File | K | p50 (s) | p95 (s) | share ending in fallback | vs. single reply p50 / p95 |")
L.append("|---|---|---|---|---|---|")
rng = random.Random(5)
for f in files:
    by_case = defaultdict(list)
    for t in turns:
        if t["file"] == f:
            by_case[(t["scenario"], t["idx"])].append(t)
    keys = list(by_case)
    base = [t["total"] for t in turns if t["file"] == f]
    for K in (2, 3):
        lat, fb = [], 0
        for _ in range(20000):
            case = by_case[rng.choice(keys)]
            el = 0.0
            ok = False
            for _k in range(K):
                t = rng.choice(case)
                el += t["total"]
                if t["ok"]:
                    ok = True
                    break
            fb += not ok
            lat.append(el)
        L.append(f"| {case[0]['short']} | {K} | {pct(lat,50):.2f} | {pct(lat,95):.2f} | {100*fb/20000:.1f}% | "
                 f"{pct(base,50):.2f} / {pct(base,95):.2f} |")

# ------------------------------------------------------------------ stop conditions
L.append("\n## Stop conditions (what if generation had stopped earlier?)\n")
L.append("Applied to clean(raw). 'acceptable' = passes the validity checks above (except the max_tokens one).\n")
L.append("| File | stop after first '?' sentence: acceptable | ...of those, an echo-only reply (<=4 content words before the question) | "
         "stop after opener + 3 sentences: acceptable | ...and still contains a question | est. time saved p50 (s) |")
L.append("|---|---|---|---|---|---|")
for f in files:
    R = [t for t in turns if t["file"] == f]
    a1 = echo = a2 = q2 = 0
    saved = []
    for t in R:
        c = S._clean(t["raw"])
        ss = [x for x in S._SENT_SPLIT.split(c) if x.strip()]
        qi = next((i for i, x in enumerate(ss) if "?" in x), None)
        if qi is not None:
            pre = " ".join(ss[:qi + 1])
            if not why_invalid(t["raw"], pre):
                a1 += 1
                before = [x for x in ss[:qi] if not S._is_opener(x)]
                if len(W(" ".join(before))) <= 4 and len(W(ss[qi])) <= 4:
                    echo += 1
                elif len(W(" ".join(before))) == 0 and len(W(ss[qi])) <= 4:
                    echo += 1
        cap = cfg.MAX_SENTENCES + (1 if len(ss) > 1 and S._is_opener(ss[0]) else 0)
        pre2 = " ".join(ss[:cap])
        if not why_invalid(t["raw"], pre2):
            a2 += 1
            q2 += "?" in pre2
        saved.append((t["total"] - t["ttft"]) * (1 - len(pre2) / max(1, len(c))))
    n = len(R)
    L.append(f"| {R[0]['short']} | {a1} ({100*a1/n:.0f}%) | {echo} | {a2} ({100*a2/n:.0f}%) | {q2} | "
             f"{statistics.median(saved):.2f} |")
L.append("\nReading: 'stop at the first question' would often end on the echo question ('Mittens?') that persona v2 "
         "teaches, so on its own it is not a good stop rule. 'Stop after N sentences' is what the old cap did and loses "
         "the final question in a large share of replies (that was the round-2 49.9% no-question problem).")

# overall
L.append("\n## Pooled\n")
for grp in ("gemma", "ministral"):
    R = [t for t in turns if (grp in t["file"]) and not (grp == "gemma" and "ministral" in t["file"])]
    L.append(f"- {grp}: pass after remove-only clean {sum(t['ok'] for t in R)}/{len(R)} "
             f"({100*sum(t['ok'] for t in R)/len(R):.1f}%), strict {sum(t['strict'] for t in R)}/{len(R)}")
write("regen.md", "\n".join(L) + "\n")
