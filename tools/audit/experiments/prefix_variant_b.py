"""Variant of prefix_filter_prototype.speak: also stop the stream right AFTER the first question sentence that has
>= 5 words (a short echo question like "Mittens?" may pass). Still prefix-only and streamable."""
import re
from _common import load_safety, load_turns, write
import prefix_filter_prototype as P
from quality import ARTIFACT, LOST, MATERIAL, classify

S, cfg = P.S, P.cfg


def speak_b(raw):
    text = S._clean(P._drop_standalone(raw))
    kept, words, content = [], 0, 0
    for s in (x for x in S._SENT_SPLIT.split(text) if x.strip()):
        if re.fullmatch(rf"(?:{S._BARE})\W*", s, re.I):
            continue
        if S._BLOCK_RE.search(s) or S.looks_private(s):
            break
        is_open = not kept and S._is_opener(s)
        n = len(s.split())
        if kept and (words + n > cfg.MAX_WORDS or (not is_open and content + 1 > cfg.MAX_SENTENCES)):
            break
        if kept and "?" in s and " ".join(kept).count("?") >= 1 and n < 5:
            break  # never a second short question
        kept.append(s)
        words += n
        content += 0 if is_open else 1
        if "?" in s and n >= 5:
            break
    while len(kept) > 1 and S._TEASER_RE.match(kept[-1].strip()):
        kept.pop()
    return " ".join(kept) if kept else S.FALLBACK


turns = load_turns()
N = len(turns)
out = [(t, h, classify(t, h, S.FALLBACK)) for t in turns for h in [speak_b(t["raw"])]]
c = lambda f: sum(1 for x in out if f(x))  # noqa: E731
lines = ["# Prefix variant B: stop after the first real question (generated by prefix_variant_b.py)\n",
         f"- material change: {c(lambda x: x[2] & MATERIAL)}/{N}",
         f"- question demoted: {c(lambda x: 'q_demoted' in x[2])}/{N}",
         f"- no '?': {c(lambda x: '?' not in x[1])}/{N}",
         f"- more than one '?': {c(lambda x: x[1].count('?') > 1)}/{N}",
         f"- any artifact or answer lost: {c(lambda x: x[2] & (ARTIFACT | LOST))}/{N}",
         f"- answer lost: {c(lambda x: 'answer_lost' in x[2])}/{N}",
         f"- avg words heard: {sum(len(x[1].split()) for x in out)/N:.1f}"]
for t, h, _ in out:
    if t["short"] == "e4b v2" and t["scenario"] == "recall" and t["sample"] == 2:
        lines.append(f"- example e4b v2 recall: {h!r}")
write("prefix_variant_b.md", "\n".join(lines) + "\n")
