"""Step 2: how much do the different definitions of "a valid Santa reply" disagree on the 924 stored raw replies?

Definitions compared (all CURRENT code):
  A  safety.check(raw) == []                          (runtime "problems" function; used by nobody at runtime)
  B  bench.rule_flags(raw) == []                      (benchmark "zero violations")
  C  sanitize(raw) needs no repair                    (what the runtime filter actually enforces)
  D  stored t["flags"] == []                          (what the result files say; computed by an older bench)
Plus per-rule comparisons (sentences, questions, length, promise, AI identity, stage directions, emoji).
"""
import random
import re
from collections import Counter

from _common import load_bench_rule_flags, load_safety, load_turns, write

S = load_safety("cur")
B = load_bench_rule_flags()
cfg = __import__("santa_cur.config", fromlist=["x"])
turns = load_turns()
N = len(turns)
random.seed(1)


def norm(s):
    return " ".join(s.split())


def safety_sentences(raw):
    """How the runtime counts sentences: after _clean, _SENT_SPLIT, leading opener is free."""
    c = S._clean(raw)
    ss = S._SENT_SPLIT.split(c)
    opener = 1 if len(ss) > 1 and S._is_opener(ss[0]) else 0
    return len(ss) - opener, ss


def bench_sentences(raw):
    return [s for s in re.split(r"(?<=[.!?])\s+", raw.strip())
            if s and not re.fullmatch(r"(ho[ ,]*)+[.!]*", s.strip(), re.I)]


rows = []
for t in turns:
    raw = t["raw"]
    a = S.check(raw)
    b = B["rule_flags"](raw)
    heard = S.sanitize(raw)
    c_ok = norm(heard) == norm(raw)
    ns, _ = safety_sentences(raw)
    nb = len(bench_sentences(raw))
    rows.append(dict(t=t, a=a, b=b, c_ok=c_ok, d=t["flags"], ns=ns, nb=nb, heard=heard,
                     words=len(raw.split()), q=raw.count("?")))


def pct(n, d=N):
    return f"{n}/{d} ({100*n/d:.1f}%)"


L = ["# Rule drift on the 924 stored raw replies (generated by rule_drift.py)\n"]
A_ok = sum(not r["a"] for r in rows)
B_ok = sum(not r["b"] for r in rows)
C_ok = sum(r["c_ok"] for r in rows)
D_ok = sum(not r["d"] for r in rows)
L.append("## Share of raw replies each definition calls valid\n")
L.append(f"- A safety.check(raw)==[]: {pct(A_ok)}")
L.append(f"- B bench.rule_flags(raw)==[] (current bench): {pct(B_ok)}")
L.append(f"- C sanitize(raw) leaves the text unchanged (whitespace-normalised): {pct(C_ok)}")
L.append(f"- D stored flags == [] (as written in the result files): {pct(D_ok)}")
L.append("\n## Pairwise disagreement (valid under one, invalid under the other)\n")
pairs = [("A", "B", lambda r: not r["a"], lambda r: not r["b"]),
         ("A", "C", lambda r: not r["a"], lambda r: r["c_ok"]),
         ("B", "C", lambda r: not r["b"], lambda r: r["c_ok"]),
         ("B", "D", lambda r: not r["b"], lambda r: not r["d"])]
ex = {}
for x, y, fx, fy in pairs:
    dis = [r for r in rows if fx(r) != fy(r)]
    L.append(f"- {x} vs {y}: {pct(len(dis))} disagree "
             f"({sum(1 for r in dis if fx(r))} valid-under-{x}-only, {sum(1 for r in dis if fy(r))} valid-under-{y}-only)")
    ex[(x, y)] = dis

# per-file
L.append("\n## Per result file: share valid under each definition\n")
L.append("| File | n | A check | B rule_flags | C no repair | D stored flags |")
L.append("|---|---|---|---|---|---|")
for f in sorted({r["t"]["file"] for r in rows}):
    R = [r for r in rows if r["t"]["file"] == f]
    n = len(R)
    L.append(f"| {R[0]['t']['short']} | {n} | {100*sum(not r['a'] for r in R)/n:.1f}% | "
             f"{100*sum(not r['b'] for r in R)/n:.1f}% | {100*sum(r['c_ok'] for r in R)/n:.1f}% | "
             f"{100*sum(not r['d'] for r in R)/n:.1f}% |")

# per rule
L.append("\n## Per-rule comparison\n")
over_s = sum(r["ns"] > cfg.MAX_SENTENCES for r in rows)
over_b = sum(r["nb"] > cfg.MAX_SENTENCES for r in rows)
dis_s = [r for r in rows if (r["ns"] > cfg.MAX_SENTENCES) != (r["nb"] > cfg.MAX_SENTENCES)]
L.append(f"- Sentence count > {cfg.MAX_SENTENCES}: runtime counting (after _clean, abbreviations, leading opener free) "
         f"{pct(over_s)}; bench counting (raw, no abbreviations, any 'ho ho' sentence free) {pct(over_b)}; "
         f"disagree on {pct(len(dis_s))}")
L.append(f"- Exact sentence counts differ on {pct(sum(r['ns'] != r['nb'] for r in rows))}")
L.append(f"- Words: check() flags > {cfg.MAX_WORDS + 5}: {pct(sum(r['words'] > cfg.MAX_WORDS + 5 for r in rows))}; "
         f"sanitize() cuts at > {cfg.MAX_WORDS}: {pct(sum(len(S._clean(r['t']['raw']).split()) > cfg.MAX_WORDS for r in rows))} "
         f"(after cleaning, before sentence cap)")
L.append(f"- More than one '?': {pct(sum(r['q'] > 1 for r in rows))} (check and rule_flags agree: same test)")
prom_b = [r for r in rows if B["PROMISE"].search(r["t"]["raw"])]
prom_s = [r for r in rows if re.search(S._PROMISE_GIFT, r["t"]["raw"], re.I)]
L.append(f"- Gift promise: bench PROMISE regex {pct(len(prom_b))}; runtime _PROMISE_GIFT {pct(len(prom_s))}; "
         f"curly-apostrophe forms (I’ll / you’ll) in raw: "
         f"{pct(sum(1 for r in rows if re.search(r'\b(?:i|you)’ll\b', r['t']['raw'], re.I)))} -- bench PROMISE has no ’")
ai_b = [r for r in rows if B["AI_ADMIT"].search(r["t"]["raw"])]
L.append(f"- AI/brand: bench AI_ADMIT hits {pct(len(ai_b))}; runtime blocklist hits {pct(sum(1 for r in rows if S._BLOCK_RE.search(r['t']['raw'])))}")
st_b = [r for r in rows if B["STAGE"].search(r["t"]["raw"])]
st_changed = [r for r in st_b if norm(S._clean(r["t"]["raw"])) != norm(r["t"]["raw"])]
emph_only = [r for r in st_b if not any(S._is_direction(m.group(1)) for m in re.finditer(r"\*+([^*]+?)\*+", r["t"]["raw"]))
             and not re.search(r"\([^)]*\)|\[[^\]]*\]", r["t"]["raw"])]
L.append(f"- Stage directions: bench STAGE (any *...*, (...), [...]) flags {pct(len(st_b))}; of those, "
         f"{len(emph_only)} contain only emphasis (*big*), which the runtime keeps as words -- bench counts them as violations")
L.append(f"- Emoji: bench EMOJI {pct(sum(1 for r in rows if B['EMOJI'].search(r['t']['raw'])))}; "
         f"runtime emoji class {pct(sum(1 for r in rows if re.search(r'[\U0001F000-\U0001FAFF☀-➿⬀-⯿‍️]', r['t']['raw'])))}")

# stored flags vs recomputed
stale = [r for r in rows if sorted(r["d"]) != sorted(r["b"])]
L.append(f"\n## Stored flags vs flags recomputed with the current bench: differ on {pct(len(stale))}")
c = Counter()
for r in stale:
    for f_ in set(r["b"]) ^ set(r["d"]):
        c[f_ + (" (new)" if f_ in r["b"] else " (gone)")] += 1
L.append("Differences by flag: " + ", ".join(f"{k}: {v}" for k, v in c.most_common()))

# stored answer vs current sanitize
st_ans = [r for r in rows if r["t"]["answer"] != r["heard"]]
L.append(f"\n## Stored `answer` (what the 23:21 run's filter produced) vs current sanitize(raw): differ on {pct(len(st_ans))}")
L.append("Every content check, the 'what the child hears' rows and the judge input in the result files use the stored "
         "answer, so they describe a filter that no longer exists.")

# examples
L.append("\n## Five examples where A (check) and B (rule_flags) disagree\n")
for r in random.sample(ex[("A", "B")], min(5, len(ex[("A", "B")]))):
    L.append(f"- [{r['t']['short']}] check={r['a']} rule_flags={r['b']} runtime_sentences={r['ns']} "
             f"bench_sentences={r['nb']}\n  - raw: {r['t']['raw'][:300]!r}")
L.append("\n## Five examples where the runtime and bench sentence counts disagree about the cap\n")
for r in random.sample(dis_s, min(5, len(dis_s))):
    _, ss = safety_sentences(r["t"]["raw"])
    L.append(f"- [{r['t']['short']}] runtime={r['ns']} bench={r['nb']}\n  - raw: {r['t']['raw'][:300]!r}\n"
             f"  - runtime split: {ss}\n  - bench split: {bench_sentences(r['t']['raw'])}")
write("rule_drift.md", "\n".join(L) + "\n")
