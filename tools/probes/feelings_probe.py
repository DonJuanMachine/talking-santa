#!/usr/bin/env python3
"""C5(c): what does Santa.remember() store when a child states a fear or a feeling? (live, ai/gemma4:e4b only)

Each line goes through the real extractor via remember() (no reply call; remember() only needs a registered child).
Prints the stored facts and the facts note Santa would see on that child's next turn. Product code unchanged.
Writes tools/probes/out/feelings_probe.md.
"""
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "out"
os.environ["SANTA_PROFILES"] = str(Path(tempfile.mkdtemp(prefix="santa-feel-")) / "profiles.json")
sys.path.insert(0, str(ROOT))

from openai import OpenAI, Timeout  # noqa: E402

from santa import config, memory, persona  # noqa: E402
from santa.brain import Santa  # noqa: E402

MODEL = "ai/gemma4:e4b"
LINES = ["i'm scared of the dark", "i'm a little bit scared of the dark", "i feel sad today", "i miss my grandma",
         "i'm scared of thunder", "i'm angry at my brother", "i'm scared of you santa", "my dog died",
         "mommy and daddy were yelling and i was scared", "i don't like going to bed by myself", "i feel happy",
         "i had a bad dream about a monster", "nobody plays with me at school", "i wet the bed last night"]


def main():
    memory.save = lambda *a, **k: None       # never write a profiles file
    subprocess.run(["docker", "model", "unload", "--all"], capture_output=True)
    time.sleep(2)
    client = OpenAI(base_url=config.BASE_URL, api_key="x", timeout=Timeout(config.REQUEST_TIMEOUT), max_retries=0)
    s = Santa(model=MODEL, client=client, profiles={})
    s.warm_up()
    L = ["# What remember() stores for fears and feelings (generated by tools/probes/feelings_probe.py)\n",
         f"Model {MODEL}, real extractor (FACTS_PROMPT, temperature 0), 2 runs per line, fresh profile per line.\n",
         "| child said | stored (run 1) | stored (run 2) | note on the child's next turn (run 1) |", "|---|---|---|---|"]
    for line in LINES:
        got = []
        for _ in range(2):
            s.profiles = {"Leo": {"facts": []}}
            s.last_reply = None
            got.append(s.remember("Leo", line))
        note = persona.facts_note("Leo", got[0]).strip() or "(none)"
        print(line, "->", got, flush=True)
        L.append(f"| {line} | {got[0] or '—'} | {got[1] or '—'} | `{note}` |")
    subprocess.run(["docker", "model", "unload", "--all"], capture_output=True)
    (OUT / "feelings_probe.md").write_text("\n".join(L) + "\n")
    print("wrote", OUT / "feelings_probe.md")


if __name__ == "__main__":
    main()
