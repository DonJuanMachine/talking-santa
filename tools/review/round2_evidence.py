#!/usr/bin/env python3
"""Evidence for round 2 (read-only, no model calls).

Replays the stored RAW model replies in evals/results/ai_*.json through the CURRENT santa.safety.sanitize_ex
(and, for comparison, through the round-1 version kept in .snapshots/pre-fix2-*), then writes
docs/history/round2_examples.md. Nothing else is written; evals/results is only read.

    <venv>/bin/python tools/review/round2_evidence.py
"""
import collections
import difflib
import glob
import importlib.util
import json
import re
import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "history" / "round2_examples.md"
sys.path.insert(0, str(ROOT))

from santa import safety  # noqa: E402  (current code)


def load_round1():
    """The round-1 santa package from the newest pre-fix2 snapshot, imported under another name.
    (santa/ has no __init__.py, so build an empty package whose __path__ is the snapshot folder.)"""
    snaps = sorted((ROOT / ".snapshots").glob("pre-fix2-*/santa/safety.py"))
    if not snaps:
        return None
    pkg = types.ModuleType("santa_round1")
    pkg.__path__ = [str(snaps[-1].parent)]
    sys.modules["santa_round1"] = pkg
    return importlib.import_module("santa_round1.safety")


def qsents(text):
    return [s for s in safety._SENT_SPLIT.split(text) if "?" in s]


def stats(replies, sanitize_ex):
    c = {"q0": 0, "q1": 0, "q2": 0, "fallback": 0, "echo": 0}
    why = collections.Counter()
    for raw in replies:
        ans, reason = sanitize_ex(raw)
        n = ans.count("?")
        c["q0" if n == 0 else "q1" if n == 1 else "q2"] += 1
        if reason:
            c["fallback"] += 1
            why[reason] += 1
        qs = qsents(ans)
        if len(qs) == 1 and ans.count("?") == 1 and len(qs[0].split()) <= 4:
            c["echo"] += 1
    return c, why


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ").strip()


def note(raw, ans, reason):
    parts = []
    if reason:
        parts.append(f"replaced by fallback ({reason})")
    else:
        rq, aq = raw.count("?"), ans.count("?")
        if rq != aq:
            parts.append(f"'?' x{rq} -> x{aq}")
        cleaned = safety._clean(raw)
        cut = len(safety._SENT_SPLIT.split(cleaned)) - len(safety._SENT_SPLIT.split(ans))
        if cut > 0:
            parts.append(f"cap removed {cut} sentence(s)")
        if safety._clean(raw) != " ".join(raw.split()):
            parts.append("markup/stage directions cleaned")
    return "; ".join(parts) or "unchanged apart from whitespace"


def main():
    files = {Path(f).name: json.load(open(f)) for f in sorted(glob.glob(str(ROOT / "evals" / "results" / "ai_*.json")))}
    rows = []   # (file, speaker, child, raw, ans, reason, change)
    for name, d in files.items():
        for t in d["turns"]:
            raw = t["raw"]
            if not raw.strip():
                continue
            ans, reason = safety.sanitize_ex(raw)
            change = 1 - difflib.SequenceMatcher(None, " ".join(raw.split()), ans).ratio()
            rows.append((name, t["speaker"], t["child"], raw, ans, reason, change))
    raws = [r[3] for r in rows]
    cur, cur_why = stats(raws, safety.sanitize_ex)
    r1mod = load_round1()
    old, old_why = stats(raws, r1mod.sanitize_ex) if r1mod else (None, None)
    raw_q = collections.Counter(min(2, r.count("?")) for r in raws)
    n = len(raws)

    def pct(x):
        return f"{x} ({100 * x / n:.1f}%)"

    md = ["# Round 2 evidence: what the child would hear",
          "",
          "Generated by `tools/review/round2_evidence.py` (read-only on `evals/results/`, no model calls).",
          f"Input: the {n} non-empty stored RAW replies from {len(files)} result files. These were generated with the "
          "v1/v2 personas, so they show what the *filter* does to old-style replies, not what persona v3 will produce.",
          "",
          "## 1. Counts",
          "",
          "| Measure | Raw model output | Round-1 sanitize | Current sanitize |",
          "|---|---|---|---|"]

    def row(label, raw_v, old_v, cur_v):
        md.append(f"| {label} | {raw_v} | {old_v} | {cur_v} |")

    row("0 question marks", pct(raw_q[0]), pct(old["q0"]) if old else "n/a", pct(cur["q0"]))
    row("exactly 1 question mark", pct(raw_q[1]), pct(old["q1"]) if old else "n/a", pct(cur["q1"]))
    row("more than 1 question mark", pct(raw_q[2]), pct(old["q2"]) if old else "n/a", pct(cur["q2"]))
    row("replaced by the fallback line", "n/a", pct(old["fallback"]) if old else "n/a", pct(cur["fallback"]))
    row("lone short echo question (only question, 4 words or fewer)", "n/a",
        pct(old["echo"]) if old else "n/a", pct(cur["echo"]))
    md += ["", "Fallback reasons (current): " + (", ".join(f"{k}: {v}" for k, v in cur_why.most_common()) or "none"),
           "",
           "Fallback reasons (round 1): " + (", ".join(f"{k}: {v}" for k, v in old_why.most_common()) or "none")
           if old else "Round-1 snapshot not found.",
           ""]

    def top(pred, k, used):
        picked = []
        for r in sorted((r for r in rows if pred(r[0])), key=lambda r: -r[6]):
            key = " ".join(r[3].split())
            if key in used:
                continue
            used.add(key)
            picked.append(r)
            if len(picked) == k:
                break
        return picked

    used = set()
    examples = (top(lambda f: f == "ai_gemma4_e4b_v2.json", 10, used) + top(lambda f: f == "ai_gemma4_v2.json", 5, used)
                + top(lambda f: "ministral" in f.lower(), 5, used))
    md += ["## 2. Twenty examples (the most-changed replies of each group)",
           "",
           "10 from `ai_gemma4_e4b_v2`, 5 from `ai_gemma4_v2`, 5 from the Ministral files; within each group the replies "
           "that the current sanitize changed the most (difflib similarity of raw vs. what the child hears).",
           "",
           "| # | File | Child said | Raw model reply | What the child would hear | What changed |",
           "|---|---|---|---|---|---|"]
    for i, (name, spk, child, raw, ans, reason, _) in enumerate(examples, 1):
        md.append(f"| {i} | {name.replace('ai_', '').replace('.json', '')} | {cell(str(spk) + ': ' + child)} | "
                  f"{cell(raw)} | {cell(ans)} | {cell(note(raw, ans, reason))} |")
    OUT.write_text("\n".join(md) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({n} replies, {len(examples)} examples)")


if __name__ == "__main__":
    main()
