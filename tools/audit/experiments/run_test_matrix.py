"""Step 1/6: run each round's test suite against each later round's code, on COPIES outside the repo.

T_x = tests/review as of version x; C_y = code (santa/, evals/ code, chat.py, scripts/) as of version y.
All runs use --runxfail so every test reports its real assertion outcome (an xfail that documents a bug
"fails" until the bug is fixed). A test that passes on its own round's code (T_x on C_x) and fails on a
later code version (T_x on C_y, y > x) was broken by a later round.

Usage: <temp venv python> run_test_matrix.py  (needs pytest in that interpreter)
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

from _common import ROOT, SNAP, write

ORDER = ["s0", "s1", "s2", "cur"]
WORK = Path(tempfile.mkdtemp(prefix="santa-audit-matrix-"))
IGN = shutil.ignore_patterns("__pycache__", "results", "backup", ".venv", ".git", ".snapshots", "transcripts",
                             "audit", "*.pyc")


def make_tree(code: str, tests: str) -> Path:
    d = WORK / f"C_{code}__T_{tests}"
    if d.exists():
        shutil.rmtree(d)
    src = SNAP[code]
    d.mkdir()
    for name in ("santa", "evals", "scripts"):
        if (src / name).exists():
            shutil.copytree(src / name, d / name, ignore=IGN)
    for name in ("chat.py", "profiles.json", "requirements.txt", "README.md"):
        if (src / name).exists():
            shutil.copy(src / name, d / name)
    (d / "evals" / "results").mkdir(parents=True, exist_ok=True)
    for f in (ROOT / "evals" / "results").glob("*.json"):  # read-only copy of the stored results
        shutil.copy(f, d / "evals" / "results" / f.name)
    shutil.copytree(SNAP[tests] / "tests" / "review", d / "tests" / "review", ignore=IGN)
    return d


def run(code: str, tests: str) -> dict:
    d = make_tree(code, tests)
    xml = d / "junit.xml"
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    subprocess.run([sys.executable, "-m", "pytest", "tests/review", "-p", "no:cacheprovider", "--runxfail", "-q",
                    f"--junitxml={xml}", "-x" if False else "--maxfail=1000"],
                   cwd=d, env=env, capture_output=True, text=True, timeout=600)
    res = {}
    for case in ET.parse(xml).getroot().iter("testcase"):
        nid = f"{case.get('classname')}::{case.get('name')}"
        if case.find("failure") is not None or case.find("error") is not None:
            msg = (case.find("failure") if case.find("failure") is not None else case.find("error")).get("message", "")
            res[nid] = ("fail", msg[:200])
        elif case.find("skipped") is not None:
            res[nid] = ("skip", "")
        else:
            res[nid] = ("pass", "")
    return res


results = {}
for i, t in enumerate(ORDER):
    for c in ORDER[i:]:
        results[(t, c)] = run(c, t)
        r = results[(t, c)]
        print(f"T_{t} on C_{c}: {sum(v[0]=='pass' for v in r.values())} pass, "
              f"{sum(v[0]=='fail' for v in r.values())} fail", flush=True)

lines = ["# Test matrix (generated by run_test_matrix.py; all runs with --runxfail, on copies outside the repo)\n",
         "| Tests from \\ Code from | " + " | ".join(ORDER) + " |", "|---|" + "---|" * len(ORDER)]
for t in ORDER:
    cells = []
    for c in ORDER:
        r = results.get((t, c))
        cells.append("" if r is None else f"{sum(v[0]=='pass' for v in r.values())} pass / "
                     f"{sum(v[0]=='fail' for v in r.values())} fail")
    lines.append(f"| T_{t} | " + " | ".join(cells) + " |")

lines.append("\n## Tests that pass on their own round's code and FAIL on a later round's code\n")
broken = {}
for i, t in enumerate(ORDER):
    own = results[(t, t)]
    for c in ORDER[i + 1:]:
        for nid, (st, msg) in results[(t, c)].items():
            if own.get(nid, ("?",))[0] == "pass" and st == "fail":
                broken.setdefault(nid, []).append((t, c, msg))
for nid, hits in sorted(broken.items()):
    first = hits[0]
    lines.append(f"- `{nid}` (written by T_{first[0]}): first breaks on C_{first[1]}; "
                 f"also on {[h[1] for h in hits[1:]]} -- `{first[2][:140]}`")
lines.append(f"\nTotal distinct tests broken by a later round: {len(broken)}")

lines.append("\n## Tests failing on the CURRENT code with the CURRENT test set (with --runxfail)\n")
for nid, (st, msg) in sorted(results[("cur", "cur")].items()):
    if st == "fail":
        lines.append(f"- `{nid}` -- `{msg[:160]}`")

# Fixed-by-round: tests failing on own code (documented bugs) that pass later
lines.append("\n## Reviewer tests (T_s0): status by code version\n")
r0 = {c: results[("s0", c)] for c in ORDER}
for c in ORDER:
    lines.append(f"- C_{c}: {sum(v[0]=='pass' for v in r0[c].values())} pass, "
                 f"{sum(v[0]=='fail' for v in r0[c].values())} fail")
write("test_matrix.md", "\n".join(lines) + "\n")
(Path(__file__).parent / "out" / "test_matrix.json").write_text(json.dumps(
    {f"{t}|{c}": v for (t, c), v in results.items()}, indent=1))
shutil.rmtree(WORK, ignore_errors=True)
