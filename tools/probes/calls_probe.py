#!/usr/bin/env python3
"""Whole calls, live: does Santa ask the same kind of question every turn, and does he greet again mid-call?

Each call starts the way the call page starts one (the canned greeting in history) at 9:30 AM, then a scripted child
says 10 things. Per reply: a question?, a question about favorites or what the child likes?, the same question as
earlier in the call?, a question right after a sad or serious turn (a loss, being hit, a secret)?, a greeting after
the first turn? Nothing is saved. Product code unchanged.

Usage: <venv>/bin/python tools/probes/calls_probe.py [--runs 3]    Writes tools/probes/out/calls_probe.md.
"""
import argparse
import copy
import os
import re
import sys
import tempfile
from datetime import datetime
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "out"
os.environ["SANTA_PROFILES"] = str(Path(tempfile.mkdtemp(prefix="santa-calls-")) / "profiles.json")
sys.path.insert(0, str(ROOT))

ap = argparse.ArgumentParser()
ap.add_argument("--runs", type=int, default=3)
A = ap.parse_args()

from santa import config, memory  # noqa: E402
from santa.brain import Santa  # noqa: E402
from santa.web import canned  # noqa: E402

KIDS = {"Emma": {"age": 4, "facts": ["likes snow angels", "has a cat named Mittens"]}, "Leo": {"age": 3, "facts": []}}
MORNING = datetime(2026, 11, 27, 9, 30)
SERIOUS = {"my goldfish died", "my brother hit me", "can you keep a secret"}
SCRIPTS = {
    "Leo": ["I'm Leo", "good", "I like trucks", "my truck is red", "I have a dog named Biscuit",
            "can I stay up and see you", "I made cookies with my mom", "my goldfish died", "okay", "I want a puppy"],
    "Emma": ["I'm Emma", "I'm good", "I made a snowman", "it has a carrot nose", "can you come to my house",
             "my brother hit me", "I like to draw", "can you keep a secret", "I want a drawing pad", "I like Mittens"],
}
QUESTION = re.compile(r"[^.!?]*\?")
LIKES = re.compile(r"\b(?:favou?rite|like to (?:play|do|eat|draw)|like best|love to (?:play|do)|like to play with"
                   r"|what kind of (?:toys?|things?|games?|animals?))\b", re.I)
GREETING = re.compile(r"^\s*(?:oh,?\s+)?(?:good (?:morning|afternoon|evening)|hello|hi\b|hey\b)", re.I)


def norm(q: str) -> str:
    q = re.sub(r"\b(?:leo|emma)\b", "", q.lower())
    return re.sub(r"[^a-z ]+", "", re.sub(r"\s+", " ", q)).strip()


def main():
    memory.save = lambda *a, **k: None
    rows, stats = [], dict(replies=0, question=0, likes=0, repeat=0, after_serious=0, serious=0, greet_mid=0)
    for run in range(A.runs):
        for kid, lines in SCRIPTS.items():
            s = Santa(profiles=copy.deepcopy(KIDS))
            s.clock = lambda: MORNING
            s.history.append({"role": "assistant", "content": canned.GREETING_SAID})
            asked = []
            for i, line in enumerate(lines):
                r = s.reply_ex(kid, line)
                qs = [q.strip() for q in QUESTION.findall(r.text)]
                likes = any(LIKES.search(q) for q in qs)
                repeat = any(norm(q) in asked for q in qs)
                greet = i > 0 and bool(GREETING.search(r.text))
                stats["replies"] += 1
                stats["question"] += bool(qs)
                stats["likes"] += likes
                stats["repeat"] += repeat
                stats["greet_mid"] += greet
                if line in SERIOUS:
                    stats["serious"] += 1
                    stats["after_serious"] += bool(qs)
                asked += [norm(q) for q in qs]
                flags = " ".join(f for f, on in [("Q", bool(qs)), ("LIKES", likes), ("REPEAT", repeat),
                                                 ("GREET", greet)] if on)
                rows.append(f"| {run + 1} | {kid} | {i + 1} | {line} | {r.text.replace('|', '/')} | {flags} |")
                print(f"[{run + 1} {kid} {i + 1}] {line} -> {r.text}  {flags}", flush=True)
    n = stats["replies"]
    head = [f"# Whole calls (generated by tools/probes/calls_probe.py)\n",
            f"Model {config.MODEL}, {A.runs} runs x {len(SCRIPTS)} children x 10 turns, 9:30 AM.\n",
            f"- replies with a question: {stats['question']}/{n}",
            f"- questions about favorites or likes: {stats['likes']}/{n}",
            f"- a question asked again in the same call: {stats['repeat']}/{n}",
            f"- a question right after a sad or serious turn: {stats['after_serious']}/{stats['serious']}",
            f"- a greeting after the first turn: {stats['greet_mid']}/{n}\n",
            "| run | child | turn | child said | Santa said | flags |", "|---|---|---|---|---|---|"]
    OUT.mkdir(exist_ok=True)
    (OUT / "calls_probe.md").write_text("\n".join(head + rows) + "\n")
    print("\n".join(head[2:7]))


if __name__ == "__main__":
    main()
