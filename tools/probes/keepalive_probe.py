#!/usr/bin/env python3
"""D3: does a lightweight request every ~165 s keep the model loaded past the runner's 5-minute idle unload?
(live, ai/gemma4:e4b only, measurement only; no product change)

1. unload --all, new Santa, warm_up() (loads the model), one real reply (baseline).
2. 12 minutes: every 165 s a ping = Santa.warm_up() (the product's own tiny request: real system prompt, "hi",
   max_tokens=1). Every 60 s: `docker model ps` and the llama-server pid (a new pid = the model was reloaded).
3. One real reply right after the 12 minutes: TTFT, first sentence, and wall time from the call (includes any
   re-warm, which TTFT does not).
4. unload --all.
Writes tools/probes/out/keepalive_probe.md and keepalive_probe.json.
"""
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "out"
os.environ["SANTA_PROFILES"] = str(Path(tempfile.mkdtemp(prefix="santa-keep-")) / "profiles.json")
sys.path.insert(0, str(ROOT))

from openai import OpenAI, Timeout  # noqa: E402

from santa import config, memory  # noqa: E402
from santa.brain import Santa  # noqa: E402

MODEL = "ai/gemma4:e4b"
RUN_S = 12 * 60
PING_EVERY = 165
CHECK_EVERY = 60


def ps():
    out = subprocess.run(["docker", "model", "ps"], capture_output=True, text=True).stdout.strip().splitlines()
    return [ln for ln in out[1:] if ln.strip()]


def pid():
    out = subprocess.run(["pgrep", "-f", "inference/llama-server"], capture_output=True, text=True).stdout.split()
    return out[0] if out else None


def reply(s, text):
    t0 = time.perf_counter()
    first_wall, sents = None, []
    for se in s.reply_stream("Emma", text):
        first_wall = first_wall if first_wall is not None else time.perf_counter() - t0
        sents.append(se)
    r = s.last_reply
    return {"child": text, "heard": r.text, "ttft": r.ttft, "first_sentence_s": r.first_sentence_s,
            "first_sentence_wall_s": first_wall, "total": r.total, "fallback": r.fallback, "reason": r.reason}


def main():
    memory.save = lambda *a, **k: None
    subprocess.run(["docker", "model", "unload", "--all"], capture_output=True)
    time.sleep(2)
    client = OpenAI(base_url=config.BASE_URL, api_key="x", timeout=Timeout(config.REQUEST_TIMEOUT), max_retries=0)
    s = Santa(model=MODEL, client=client, profiles={"Emma": {"facts": []}})
    s.set_active("Emma")
    ok = s.warm_up()
    res = {"warmup_ok": ok, "warmup_s": s.last_warmup_seconds, "pid_start": pid()}
    res["baseline"] = reply(s, "hi santa! do reindeer like snow?")
    print("warm-up", ok, f"{s.last_warmup_seconds:.1f}s, pid", res["pid_start"], "| baseline", res["baseline"], flush=True)
    t_start = time.monotonic()
    next_ping, next_check = PING_EVERY, 0
    checks, pings = [], []
    while True:
        el = time.monotonic() - t_start
        if el >= next_check:
            checks.append({"t": round(el), "ps": ps(), "pid": pid()})
            print(f"[{el:6.0f}s] ps={checks[-1]['ps']} pid={checks[-1]['pid']}", flush=True)
            next_check += CHECK_EVERY
        if el >= next_ping:
            ok = s.warm_up()
            pings.append({"t": round(el), "ok": ok, "s": round(s.last_warmup_seconds, 3), "pid": pid()})
            print(f"[{el:6.0f}s] ping ok={ok} {s.last_warmup_seconds:.3f}s pid={pings[-1]['pid']}", flush=True)
            next_ping += PING_EVERY
        if el >= RUN_S:
            break
        time.sleep(1)
    res["checks"], res["pings"] = checks, pings
    res["since_last_ping_s"] = round(time.monotonic() - t_start - pings[-1]["t"]) if pings else None
    res["pid_before_reply"] = pid()
    res["after"] = reply(s, "what is your favourite cookie?")
    res["pid_end"] = pid()
    print("after", res["after"], "pid", res["pid_end"], flush=True)
    subprocess.run(["docker", "model", "unload", "--all"], capture_output=True)

    pids = {c["pid"] for c in checks} | {p["pid"] for p in pings} | {res["pid_start"], res["pid_end"]}
    loaded_all = all(c["ps"] for c in checks)
    b, a = res["baseline"], res["after"]
    L = ["# D3 keep-alive probe (generated by tools/probes/keepalive_probe.py)\n",
         f"Model {MODEL}. Ping = `Santa.warm_up()` (real system prompt + \"hi\", max_tokens=1) every {PING_EVERY} s; "
         f"`docker model ps` + llama-server pid every {CHECK_EVERY} s; {RUN_S // 60} minutes.\n",
         f"- model listed by `docker model ps` at every check: **{loaded_all}** ({sum(1 for c in checks if c['ps'])}/{len(checks)})",
         f"- llama-server pids seen: {sorted(p for p in pids if p)} ({'same process the whole time' if len(pids - {None}) == 1 else 'CHANGED'})",
         f"- initial warm-up (cold load): {res['warmup_s']:.2f} s",
         f"- pings: " + ", ".join(f"t={p['t']}s {p['s']:.3f}s" for p in pings),
         f"- reply after {RUN_S // 60} min ({res['since_last_ping_s']} s after the last ping): TTFT {a['ttft']:.2f} s, "
         f"first sentence {a['first_sentence_s']:.2f} s, wall time to first sentence {a['first_sentence_wall_s']:.2f} s, "
         f"fallback {a['fallback']}",
         f"- baseline reply at the start (turn 0 right after warm-up): TTFT {b['ttft']:.2f} s, first sentence "
         f"{b['first_sentence_s']:.2f} s\n",
         "| t (s) | docker model ps | pid |", "|---|---|---|"]
    for c in checks:
        L.append(f"| {c['t']} | {' / '.join(' '.join(x.split()) for x in c['ps']) or '(empty)'} | {c['pid']} |")
    L += ["", f"Baseline: Emma: {b['child']} → {b['heard']}", f"After: Emma: {a['child']} → {a['heard']}"]
    (OUT / "keepalive_probe.md").write_text("\n".join(L) + "\n")
    (OUT / "keepalive_probe.json").write_text(json.dumps(res, indent=1, ensure_ascii=False))
    print("wrote", OUT / "keepalive_probe.md")


if __name__ == "__main__":
    main()
