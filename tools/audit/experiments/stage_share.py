"""Share of raw replies per model family that contain a stage direction (an action-only span, or a stand-alone
*span*/(span) that is not just sound words)."""
import re
from _common import SOUNDS, W, load_safety, load_turns, standalone_spans, write

S = load_safety("cur")
T = load_turns()
L = ["# Stage directions in raw replies (generated by stage_share.py)\n"]
for fam in ["ministral", "gemma4-e4b", "gemma4-12B"]:
    R = [t for t in T if t["family"] == fam]
    n = 0
    for t in R:
        spans = [m.group(1) or m.group(2) for m in re.finditer(r"\*+([^*]+?)\*+|\(([^)]*)\)", t["raw"])]
        act = any(S._is_direction(s) for s in spans)
        alone = any(W(i) and not all(w in SOUNDS for w in W(i)) for i in standalone_spans(t["raw"]))
        n += act or alone
    L.append(f"- {fam}: {n}/{len(R)} ({100*n/len(R):.0f}%)")
write("stage_share.md", "\n".join(L) + "\n")
