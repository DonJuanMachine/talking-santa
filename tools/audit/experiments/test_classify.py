"""Step 6: classify every test function in tests/review (current) by kind, with AST heuristics.

Kinds (first match wins):
  harness     tests of the benchmark/reporting code (bench fixture, sandbox, bench.*, bench_all.sh, MANIFEST)
  snapshot    asserts equality with a literal of >= 3 words / >= 20 chars, or endswith/startswith a literal row,
              or equality with a literal list of sentences (pins exact text)
  mock        uses FakeClient/make_santa/monkeypatch and asserts on calls or object state
  property    iterates over the stored corpus or many generated inputs and asserts only relations/limits
  example     everything else: specific input -> asserts a fragment is (not) in the output
Also counts parametrized cases (from the test matrix run) and tests asserting exact sanitize output.
"""
import ast
import json
from collections import Counter, defaultdict
from pathlib import Path

from _common import ROOT, write

TESTS = ROOT / "tests" / "review"
matrix = json.loads((Path(__file__).parent / "out" / "test_matrix.json").read_text())["cur|cur"]
cases_per_fn = Counter(k.split("::")[1].split("[")[0] for k in matrix)


def literal_strs(node):
    return [n.value for n in ast.walk(node) if isinstance(n, ast.Constant) and isinstance(n.value, str)]


def kind(fn, code, fname):
    src = ast.get_source_segment(code, fn)
    args = {a.arg for a in fn.args.args}
    if fname in ("test_bench.py", "test_fixes_bench.py") or args & {"bench", "sandbox"} or "bench." in src \
            or "bench_all" in src or "MANIFEST" in src or "export" in fn.name:
        return "harness"
    exact = False
    for n in ast.walk(fn):
        if isinstance(n, ast.Compare) and any(isinstance(o, ast.Eq) for o in n.ops):
            for side in [n.left] + n.comparators:
                if isinstance(side, ast.Constant) and isinstance(side.value, str) and \
                        (len(side.value.split()) >= 3 or len(side.value) >= 20):
                    exact = True
                if isinstance(side, (ast.List, ast.Tuple)) and any(
                        isinstance(e, ast.Constant) and isinstance(e.value, str) and len(e.value.split()) >= 2
                        for e in side.elts):
                    exact = True
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and n.func.attr in ("endswith", "startswith") \
                and n.args and isinstance(n.args[0], ast.Constant) and "|" in str(n.args[0].value):
            exact = True
    if exact:
        return "snapshot"
    if args & {"make_santa", "tmp_profiles", "monkeypatch"} or "FakeClient" in src:
        return "mock"
    if "results" in src and ("glob" in src or "for " in src) or "random" in src or "hypothesis" in src:
        return "property"
    return "example"


rows = []
for p in sorted(TESTS.glob("test_*.py")):
    code = p.read_text()
    for fn in ast.walk(ast.parse(code)):
        if isinstance(fn, ast.FunctionDef) and fn.name.startswith("test_"):
            src = ast.get_source_segment(code, fn)
            k = kind(fn, code, p.name)
            sanitize_exact = k == "snapshot" and ("sanitize" in src or "_truncate" in src or "_one_question" in src)
            rows.append({"file": p.name, "fn": fn.name, "kind": k, "cases": cases_per_fn.get(fn.name, 1),
                         "sanitize_exact": sanitize_exact,
                         "report_text": "report" in src and k in ("snapshot", "harness") and ("md" in src or "line" in src)})

L = ["# Test-suite classification (generated by test_classify.py; AST heuristics, see docstring)\n"]
L.append("| File | functions | cases | harness | snapshot | mock | property | example |")
L.append("|---|---|---|---|---|---|---|---|")
by = defaultdict(list)
for r in rows:
    by[r["file"]].append(r)
tot = Counter()
for f, R in by.items():
    c = Counter(r["kind"] for r in R)
    tot.update(c)
    L.append(f"| {f} | {len(R)} | {sum(r['cases'] for r in R)} | {c['harness']} | {c['snapshot']} | {c['mock']} | "
             f"{c['property']} | {c['example']} |")
L.append(f"| **total** | {len(rows)} | {sum(r['cases'] for r in rows)} | {tot['harness']} | {tot['snapshot']} | "
         f"{tot['mock']} | {tot['property']} | {tot['example']} |")
L.append(f"\nTests asserting an exact sanitize/_truncate/_one_question output string: "
         f"{sum(r['sanitize_exact'] for r in rows)} functions: "
         + ", ".join(f"`{r['file']}::{r['fn']}`" for r in rows if r["sanitize_exact"]))
L.append(f"\nTests that read the real stored corpus (evals/results) and assert a rate/limit: "
         + ", ".join(f"`{r['file']}::{r['fn']}`" for r in rows if r["kind"] == "property"))
L.append("\n## Full list\n")
for r in rows:
    L.append(f"- {r['kind']:9s} `{r['file']}::{r['fn']}` ({r['cases']} case(s))")
write("test_classify.md", "\n".join(L) + "\n")
