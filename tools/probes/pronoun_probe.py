#!/usr/bin/env python3
"""D4: does the real extractor add a gendered pronoun to a stored fact? (live, ai/gemma4:e4b only, measurement only)

Emma and Leo each say "i don't like going to bed by myself", 3 runs each, fresh profile per run, through
Santa.remember() (the real extractor: FACTS_PROMPT with the child's name, temperature 0). Prints the stored facts
verbatim and flags he/she/him/her/his/hers/himself/herself/boy/girl. Product code unchanged.
Writes tools/probes/out/pronoun_probe.md and pronoun_probe.json.
"""
import json
import os
import re
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / "out"
os.environ["SANTA_PROFILES"] = str(Path(tempfile.mkdtemp(prefix="santa-pron-")) / "profiles.json")
sys.path.insert(0, str(ROOT))

from openai import OpenAI, Timeout  # noqa: E402

from santa import config, memory, persona  # noqa: E402
from santa.brain import Santa  # noqa: E402

MODEL = "ai/gemma4:e4b"
LINE = "i don't like going to bed by myself"
CHILDREN = ["Emma", "Leo"]
RUNS = 3
GENDERED = re.compile(r"\b(he|she|him|her|his|hers|himself|herself|boy|girl)\b", re.I)


def main():
    memory.save = lambda *a, **k: None       # never write a profiles file
    subprocess.run(["docker", "model", "unload", "--all"], capture_output=True)
    time.sleep(2)
    client = OpenAI(base_url=config.BASE_URL, api_key="x", timeout=Timeout(config.REQUEST_TIMEOUT), max_retries=0)
    s = Santa(model=MODEL, client=client, profiles={})
    ok = s.warm_up()
    rows = []
    for child in CHILDREN:
        for run in range(RUNS):
            s.profiles = {child: {"facts": []}}
            s.last_reply = None
            got = s.remember(child, LINE)
            hits = sorted({m.group(1).lower() for f in got for m in GENDERED.finditer(f)})
            rows.append({"child": child, "run": run + 1, "stored": got, "gendered": hits,
                         "note": persona.facts_note(child, got).strip()})
            print(child, run + 1, "->", got, "gendered:", hits or "none", flush=True)
    subprocess.run(["docker", "model", "unload", "--all"], capture_output=True)
    L = ["# D4 pronoun probe (generated by tools/probes/pronoun_probe.py)\n",
         f"Model {MODEL}, real extractor via `Santa.remember()` (FACTS_PROMPT with the child's name, temperature 0), "
         f"{RUNS} runs per child, fresh profile per run. Warm-up ok={ok}. Child said: `{LINE}`\n",
         "| child | run | stored (verbatim) | gendered word | facts note on the next turn |", "|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['child']} | {r['run']} | {json.dumps(r['stored'], ensure_ascii=False)} | "
                 f"{', '.join(r['gendered']) or 'none'} | `{r['note'] or '(none)'}` |")
    (OUT / "pronoun_probe.md").write_text("\n".join(L) + "\n")
    (OUT / "pronoun_probe.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False))
    print("wrote", OUT / "pronoun_probe.md")


if __name__ == "__main__":
    main()
